"""Convert the supplied, licensed Phosphor SVG paths to native Flutter vectors."""
import re
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ICONS = {
    'add_photo_alternate_outlined': 'image-light',
    'door_front_door_outlined': 'door-open-light',
    'account_circle_outlined': 'user-circle-light',
    'language': 'globe-simple-light',
    'lock_outline': 'lock-simple-light',
    'arrow_back': 'arrow-left', 'arrow_forward': 'arrow-right',
    'bookmark': 'bookmark-simple-fill', 'bookmark_border': 'bookmark-simple-light',
    'calendar_month': 'calendar-blank-light', 'event_outlined': 'calendar-blank-light',
    'close': 'x-light', 'key_outlined': 'key-light',
    'keyboard_arrow_down': 'caret-down', 'menu': 'list-light',
    'north_east': 'arrow-up-right', 'person_outline': 'user-light',
    'place_outlined': 'map-pin-light', 'radio_button_checked': 'users-three-light',
    'refresh': 'arrow-clockwise', 'search': 'magnifying-glass-light',
    'visibility_outlined': 'eye-light',
}

def convert(data):
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?', data)
    count = dict(M=2, L=2, H=1, V=1, C=6, Q=4, S=4, T=2, A=7, Z=0)
    out, i, command, x, y, sx, sy = [], 0, None, 0., 0., 0., 0.
    number = lambda n: str(float(n))
    previous, control = None, (0., 0.)
    while i < len(tokens):
        if tokens[i].isalpha():
            command = tokens[i]
            i += 1
        upper, relative = command.upper(), command.islower()
        if upper not in count:
            raise ValueError(f'Unsupported SVG command {command}')
        n = count[upper]
        values = [float(v) for v in tokens[i:i+n]]
        i += n
        if upper == 'Z':
            out.append('..close()')
            x, y = sx, sy
            command = None
            previous = 'Z'
            continue
        args = ', '.join(map(number, values))
        if upper in ('M', 'L'):
            x, y = (x+values[0], y+values[1]) if relative else values
            method = 'moveTo' if upper == 'M' else 'lineTo'
            out.append(f'..{method}({number(x)}, {number(y)})')
            if upper == 'M':
                sx, sy = x, y
                command = 'l' if relative else 'L'
        elif upper in ('H', 'V'):
            if upper == 'H': x = x+values[0] if relative else values[0]
            else: y = y+values[0] if relative else values[0]
            out.append(f'..lineTo({number(x)}, {number(y)})')
        elif upper in ('C', 'Q', 'S', 'T'):
            if upper in ('S', 'T'):
                reflected = (2*x-control[0], 2*y-control[1]) if previous in (('C', 'S') if upper=='S' else ('Q', 'T')) else (x,y)
                absolute = [v+(x if j%2==0 else y) for j,v in enumerate(values)] if relative else values
                values = [*reflected, *absolute]
                relative = False
                args = ', '.join(map(number, values))
            control = (x+values[-4], y+values[-3]) if relative else tuple(values[-4:-2])
            method = ('relative' if relative else '') + ('CubicTo' if upper in ('C', 'S') else 'QuadraticBezierTo')
            method = method[0].lower() + method[1:]
            out.append(f'..{method}({args})')
            x, y = (x+values[-2], y+values[-1]) if relative else values[-2:]
        elif upper == 'A':
            rx, ry, rotation, large, sweep, px, py = values
            method = 'relativeArcToPoint' if relative else 'arcToPoint'
            out.append(f'..{method}(Offset({px}, {py}), radius: Radius.elliptical({rx}, {ry}), rotation: {rotation}, largeArc: {str(bool(large)).lower()}, clockwise: {str(bool(sweep)).lower()})')
            x, y = (x+px, y+py) if relative else (px, py)
        previous = upper
    return '\n'.join(out)

output = ["// Generated by tool/generate_phosphor.py. Phosphor Icons, MIT (assets/icons/phosphor/LICENSE.txt).", "import 'package:flutter/material.dart';", 'final Map<IconData, Path> phosphorVectors = {']
for icon, source in ICONS.items():
    root = ET.parse(ROOT / f'assets/icons/phosphor/{source}.svg').getroot()
    paths = root.findall('{http://www.w3.org/2000/svg}path')
    assert len(paths) == len(root), f'Non-path SVG element in {source}'
    output.append(f'Icons.{icon}: Path()')
    for path in paths:
        output.append(convert(path.attrib['d']))
    output.append(',')
output.append('};')
(ROOT / 'lib/phosphor_vectors.dart').write_text('\n'.join(output)+'\n')
