"""Generate Flutter constants from the supplied Aushang 3 token source."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'client/design/aushang3.tokens.json'
OUTPUT = ROOT / 'client/lib/aushang_tokens.dart'


def generate():
    tree = json.loads(SOURCE.read_text())
    leaves = {}

    def walk(node, path=()):
        if not isinstance(node, dict):
            return
        if '$value' in node:
            leaves['.'.join(path)] = node['$value']
        else:
            for key, child in node.items():
                walk(child, (*path, key))

    walk(tree)

    def resolve(value, visited=()):
        if isinstance(value, str) and value.startswith('{'):
            key = value[1:-1]
            if key in visited:
                raise ValueError('Circular token reference')
            return resolve(leaves[key], (*visited, key))
        return value

    lines = [
        '// Generated by scripts/generate_aushang_tokens.py. Edit the JSON source.',
        "import 'package:flutter/material.dart';",
        '',
        'abstract final class AushangTokens {',
    ]
    for path, value in leaves.items():
        parts = re.split(r'[.\-]', path)
        name = parts[0] + ''.join(p.capitalize() for p in parts[1:])
        value = str(resolve(value))
        if value.startswith('#'):
            dart = 'Color(0xFF' + value[1:] + ')'
        elif value.endswith('ms'):
            dart = 'Duration(milliseconds: ' + value[:-2] + ')'
        elif value.endswith('px'):
            dart = str(float(value[:-2]))
        elif value.startswith('cubic-bezier('):
            dart = 'Cubic(' + value[13:-1] + ')'
        elif re.fullmatch(r'-?\d+(\.\d+)?', value):
            dart = str(float(value))
        else:
            dart = json.dumps(value)
        lines.append(f'  static const {name} = {dart};')
    lines.append('}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    if args.check:
        # Dart formatting is cosmetic; token declarations must remain identical.
        actual = OUTPUT.read_text()
        if re.sub(r'\s+', '', actual) != re.sub(r'\s+', '', expected):
            raise SystemExit('Generated Aushang tokens are out of date')
        print('Aushang token source and generated constants match.')
    else:
        OUTPUT.write_text(expected)
